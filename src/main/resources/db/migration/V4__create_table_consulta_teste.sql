CREATE TABLE consulta_teste (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    consulta_id    BIGINT NOT NULL,
    teste_id       BIGINT NOT NULL,
    qtd            INTEGER NOT NULL,
    custo_unitario NUMERIC(10,2) NOT NULL,

    CONSTRAINT fk_consulta_teste_consulta FOREIGN KEY (consulta_id) REFERENCES consulta (id),
    CONSTRAINT fk_consulta_teste_teste FOREIGN KEY (teste_id) REFERENCES teste_psicologico (id)
);
